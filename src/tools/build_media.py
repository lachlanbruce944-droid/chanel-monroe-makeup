"""Builds data/media.js for the site from the image and video folders.
Run from anywhere:  python tools/build_media.py
Sources (relative to the final-draft folder):
  images/chanel/index.csv            Chanel's own photos (plus OWN below for group / style / description)
  images/inspiration/credits.csv     style-reference photos by other artists (one folder per style)
  images/inspiration/lip-credits.csv Lip art references
  images/videos/videos.csv           short clips (video-only, no audio)
"""
import csv, json, os, urllib.parse
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GROUPS = {
 'natural': ['No-makeup makeup','Clean polished','Fresh lift','Dewy glass skin','Sun-kissed bronze','Mature natural','Sensitive skin','Maternity glow','Makeup lesson'],
 'glam': ['Soft glam','Full glam','Bronzed coastal glam','Old Hollywood','Race day glam','Mature skin glam'],
 'bridal': ['Classic bridal','Natural radiant bride','Groom grooming'],
 'editorial': ['Beauty close-up','Graphic liner','Editorial graphic liner','Colour block and gloss','Lip art','Avant-garde','Music video and album art','Stage and theatre'],
 'fx': ['SFX and prosthetics','Body paint','Cosplay recreation','Halloween character','Fancy dress','UV neon'],
 'parties': ['Glitter bar and gems','Kids face paint','Express designs','Easter','Christmas and New Year','Holiday specials']}
S2G = {s: g for g, ss in GROUPS.items() for s in ss}
OWN = {
 'sunset-glam': ('glam','Full glam','Golden-hour glam with warm, sculpted skin'),
 'circus-character': ('fx','Fancy dress','A little circus: graphic liner and theatrical colour'),
 'red-hot-glamour': ('editorial','Colour block and gloss','Red-hot editorial glamour'),
 'clown': ('fx','Halloween character','Clown character for Halloween'),
 'gypsy-witch-competition': ('fx','Halloween character','Gypsy witch, a competition look'),
 'sinner-dark-creature': ('fx','Halloween character','Sinner: red-cross gothic glam with a studded collar'),
 'ghoulish-glam': ('fx','SFX and prosthetics','A ghoulish creature in full SFX'),
 'fairy-tale': ('fx','Fancy dress','Fairy-tale glitter and pastel colour'),
 'soft-bronzed-glam': ('glam','Bronzed coastal glam','Soft, bronzed and beautifully blended'),
 'pink-lip-party-glam': ('parties','Glitter bar and gems','Party glam with a pink lip and sparkle'),
 '21st-birthday-glam': ('glam','Soft glam','21st birthday glam'),
 'night-out-glam': ('glam','Soft glam','Night-out glam'),
 'blue-ice': ('editorial','Avant-garde','Blue Ice: frosted editorial'),
 'glam-selfie': ('natural','Clean polished','Polished everyday glow'),
 'barbie-makeover': ('glam','Soft glam','Barbie makeover in soft pinks'),
 'sunkissed-shoot': ('natural','Sun-kissed bronze','Sun-kissed shoot on location'),
 'scared-to-love-male-model': ('editorial','Beauty close-up','Scared to Love: men’s editorial'),
 'male-model-portrait': ('editorial','Beauty close-up','Men’s editorial portrait')}
def url(p): return urllib.parse.quote(os.path.relpath(p, ROOT).replace('\\', '/'))
def rows(p): return list(csv.DictReader(open(p, encoding='utf-8-sig', newline=''))) if os.path.exists(p) else []
out = []
for r in rows(os.path.join(ROOT, 'images', 'chanel', 'index.csv')):
    rel = r['file'].replace('Styles/', '', 1); p = os.path.join(ROOT, 'images', 'chanel', *rel.split('/'))
    label = os.path.splitext(os.path.basename(rel))[0].split('_', 2)[-1]
    if label not in OWN or not os.path.exists(p): continue
    g, s, d = OWN[label]
    out.append(dict(type='img', g=g, s=s, src=url(p), by='@chanelmonroemakeup', post=r['post_url'], own=1, d=d, w=int(r['width']), h=int(r['height'])))
for csvname in ('credits.csv', 'lip-credits.csv'):
    for r in rows(os.path.join(ROOT, 'images', 'inspiration', csvname)):
        style = r['style']; name = os.path.basename(r['file']); folder = os.path.join(ROOT, 'images', 'inspiration', style)
        p = os.path.join(folder, name)
        if not os.path.exists(p): p = os.path.splitext(p)[0] + '.webp'
        if not os.path.exists(p) or style not in S2G: continue
        out.append(dict(type='img', g=S2G[style], s=style, src=url(p), by=r['artist'], post=r['post_url'], own=0, w=int(r['width'] or 0), h=int(r['height'] or 0)))
for r in rows(os.path.join(ROOT, 'images', 'videos', 'videos.csv')):
    p = os.path.join(ROOT, 'images', 'videos', r['file']); th = os.path.join(ROOT, 'images', 'videos', r['poster'])
    if not os.path.exists(p): continue
    out.append(dict(type='video', g=r['group'], s=r['style'], src=url(p), poster=url(th) if os.path.exists(th) else '', by=r['artist'], post=r['post_url'], own=0, w=int(r['width']), h=int(r['height']), dur=float(r['seconds'])))
with open(os.path.join(ROOT, 'data', 'media.js'), 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/build_media.py: do not edit by hand. Use Edit mode (data/overrides.js) for manual changes. */\n')
    f.write('window.MEDIA = ' + json.dumps(out, ensure_ascii=False) + ';\n')
counts = {}
for x in out:
    k = x['g'] + ('/video' if x['type'] == 'video' else ''); counts[k] = counts.get(k, 0) + 1
print(len(out), 'items', counts)
